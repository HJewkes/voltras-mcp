// Pure half of `scripts/token-budget.mjs` (VW-831): the offline token
// estimator, the committed table's render and parse, and the budget compare.
// Nothing here boots a server or touches the filesystem, so the check is
// testable without one.

/** Characters per token for numeric JSON (VW-807 plan, measured push-event deltas). */
export const CHARS_PER_TOKEN_JSON = 1.9;
/** Characters per token for prose (VW-807 plan, English description text). */
export const CHARS_PER_TOKEN_PROSE = 3.8;
/** How far a row or a journey may grow over the committed table before `--check` fails. */
export const GROWTH_TOLERANCE = 0.05;
/** A fraction this short reads as a rounded value; a longer one as a full-precision float. */
const ROUNDED_FRACTION_DIGITS = 3;
/** Every rounded non-integer is counted at this width (`0.000`). */
const ROUNDED_NUMBER = '0.000';
/** Every full-precision non-integer is counted at this width, a double's shortest round trip. */
const FULL_PRECISION_NUMBER = `0.${'0'.repeat(16)}`;

/** Split a text into prose and numeric-JSON characters. Non-JSON text is all prose. */
export function classifyChars(text) {
  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch {
    return { prose: text.length, json: 0 };
  }
  if (parsed === null || typeof parsed !== 'object') return { prose: 0, json: text.length };
  const prose = proseCharsIn(parsed);
  return { prose, json: text.length - prose };
}

/** JSON-encoded length of every string value that reads as prose (holds a space). */
function proseCharsIn(value) {
  if (typeof value === 'string') return value.includes(' ') ? JSON.stringify(value).length : 0;
  if (value === null || typeof value !== 'object') return 0;
  let total = 0;
  for (const child of Object.values(value)) total += proseCharsIn(child);
  return total;
}

/** Count each non-integer by precision class alone, so mock timing jitter never moves a count. */
export function normalizeNumbers(text) {
  return text.replace(/(?<![\w.])-?\d+\.(\d+)(e[-+]?\d+)?(?![\w.])/gi, (_, fraction, exponent) =>
    fraction.length <= ROUNDED_FRACTION_DIGITS && exponent === undefined
      ? ROUNDED_NUMBER
      : FULL_PRECISION_NUMBER,
  );
}

/** Estimated tokens for one text, as a fraction; round only at the row. */
export function estimateTokens(text) {
  const { prose, json } = classifyChars(normalizeNumbers(text));
  return prose / CHARS_PER_TOKEN_PROSE + json / CHARS_PER_TOKEN_JSON;
}

/** Fold measured texts into one sorted row per key: count, characters, total and max tokens. */
export function summarize(samples) {
  const rows = new Map();
  for (const { key, text } of samples) {
    const row = rows.get(key) ?? { key, count: 0, chars: 0, tokens: 0, max: 0 };
    const tokens = estimateTokens(text);
    row.count += 1;
    row.chars += normalizeNumbers(text).length;
    row.tokens += tokens;
    row.max = Math.max(row.max, tokens);
    rows.set(key, row);
  }
  return [...rows.values()]
    .map((row) => ({ ...row, tokens: Math.round(row.tokens), max: Math.round(row.max) }))
    .sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

/** One `tools/list` row per tool, measured on the tool's whole advertised JSON. */
export function toolsListRows(tools) {
  return summarize(tools.map((tool) => ({ key: tool.name, text: JSON.stringify(tool) }))).map(
    ({ key, chars, tokens }) => ({ key, chars, tokens }),
  );
}

const totalOf = (rows) => rows.reduce((sum, row) => sum + row.tokens, 0);

/** A budget's headline numbers: one per section, plus each journey's sum. */
export function budgetTotals(budget) {
  const totals = { 'tools/list': totalOf(budget.toolsList) };
  for (const journey of budget.journeys) {
    totals[`${journey.name} responses`] = totalOf(journey.responses);
    totals[`${journey.name} push events`] = totalOf(journey.pushEvents);
    totals[`${journey.name} total`] = totalOf(journey.responses) + totalOf(journey.pushEvents);
  }
  return totals;
}

const TOOLS_LIST = 'tools/list';
const RESPONSES = 'tool responses';
const PUSH_EVENTS = 'push events';

const HEADER = [
  '# Token budget',
  '',
  '<!-- Generated by `node scripts/token-budget.mjs`. Regenerate it; never edit it by hand. -->',
  '',
  'What the voltras-mcp surface costs a client in context, measured on the mock adapter over',
  'a seeded store with a pinned clock (VW-831). Tokens are an offline estimate: JSON structure',
  `and numbers at ${CHARS_PER_TOKEN_JSON} characters per token, prose strings at ${CHARS_PER_TOKEN_PROSE}.`,
  'Non-integers count at a fixed width per precision class, so mock timing jitter never moves a row.',
  '',
  `\`npm run budget:check\` fails when a journey total or one row's largest response (\`Max\`)`,
  `grows more than ${GROWTH_TOLERANCE * 100}% over this table, or when a row is new.`,
];

const row = (cells) => `| ${cells.join(' | ')} |`;

function renderTable(heading, columns, rows, cellsOf) {
  return [
    `## ${heading}`,
    '',
    row(columns),
    row(columns.map((_, index) => (index === 0 ? '---' : '--:'))),
    ...rows.map((entry) => row(cellsOf(entry))),
  ];
}

const journeyCells = (entry) => [
  `\`${entry.key}\``,
  entry.count,
  entry.chars,
  entry.tokens,
  entry.max,
];

/** The committed `docs/token-budget.md`, one row per tool, call or event, sorted. */
export function renderBudget(budget) {
  const totals = Object.entries(budgetTotals(budget));
  const sections = [
    renderTable('Totals', ['Budget', 'Tokens'], totals, ([name, tokens]) => [name, tokens]),
    renderTable(TOOLS_LIST, ['Tool', 'Characters', 'Tokens'], budget.toolsList, (entry) => [
      `\`${entry.key}\``,
      entry.chars,
      entry.tokens,
    ]),
  ];
  for (const journey of budget.journeys) {
    const columns = ['Count', 'Characters', 'Tokens', 'Max'];
    sections.push(
      renderTable(
        `${journey.name}: ${RESPONSES}`,
        ['Call', ...columns],
        journey.responses,
        journeyCells,
      ),
      renderTable(
        `${journey.name}: ${PUSH_EVENTS}`,
        ['Event', ...columns],
        journey.pushEvents,
        journeyCells,
      ),
    );
  }
  return `${[HEADER, ...sections].map((lines) => lines.join('\n')).join('\n\n')}\n`;
}

/** Rows of every `## heading` table whose first cell is a backticked key. */
function readSections(markdown) {
  const sections = new Map();
  let current = null;
  for (const line of markdown.split('\n')) {
    if (line.startsWith('## ')) {
      current = [];
      sections.set(line.slice(3).trim(), current);
      continue;
    }
    const cells = /^\|\s*`([^`]+)`\s*\|(.*)\|\s*$/.exec(line);
    if (current === null || cells === null) continue;
    current.push([cells[1], ...cells[2].split('|').map((cell) => Number(cell.trim()))]);
  }
  return sections;
}

/** Parse a committed table back into the shape {@link renderBudget} takes. */
export function parseBudget(markdown) {
  const sections = readSections(markdown);
  const toolsList = (sections.get(TOOLS_LIST) ?? []).map(([key, chars, tokens]) => ({
    key,
    chars,
    tokens,
  }));
  const journeyRows = (heading) =>
    (sections.get(heading) ?? []).map(([key, count, chars, tokens, max]) => ({
      key,
      count,
      chars,
      tokens,
      max,
    }));
  const names = [...sections.keys()]
    .filter((heading) => heading.endsWith(`: ${RESPONSES}`))
    .map((heading) => heading.slice(0, -`: ${RESPONSES}`.length));
  const journeys = names.map((name) => ({
    name,
    responses: journeyRows(`${name}: ${RESPONSES}`),
    pushEvents: journeyRows(`${name}: ${PUSH_EVENTS}`),
  }));
  return { toolsList, journeys };
}

const overBudget = (current, committed) => current > committed * (1 + GROWTH_TOLERANCE);

/** Rows that are new, or whose `field` grew past the tolerance. */
function rowFailures(label, committedRows, currentRows, field) {
  const committed = new Map(committedRows.map((entry) => [entry.key, entry]));
  const failures = [];
  for (const entry of currentRows) {
    const before = committed.get(entry.key);
    const name = `${label} \`${entry.key}\``;
    if (before === undefined) failures.push(`${name}: new row, ${entry[field]} tokens`);
    else if (overBudget(entry[field], before[field])) {
      failures.push(`${name}: ${before[field]} -> ${entry[field]} tokens`);
    }
  }
  return failures;
}

/** Every way `current` breaks the `committed` budget; empty means the check passes. */
export function compareBudgets(committed, current) {
  const failures = rowFailures(TOOLS_LIST, committed.toolsList, current.toolsList, 'tokens');
  for (const journey of current.journeys) {
    const before = committed.journeys.find((entry) => entry.name === journey.name) ?? {
      responses: [],
      pushEvents: [],
    };
    failures.push(
      ...rowFailures(`${journey.name} response`, before.responses, journey.responses, 'max'),
      ...rowFailures(`${journey.name} push event`, before.pushEvents, journey.pushEvents, 'max'),
    );
  }
  const committedTotals = budgetTotals(committed);
  for (const [name, tokens] of Object.entries(budgetTotals(current))) {
    const before = committedTotals[name];
    if (before !== undefined && overBudget(tokens, before)) {
      failures.push(`${name}: ${before} -> ${tokens} tokens`);
    }
  }
  return failures;
}
