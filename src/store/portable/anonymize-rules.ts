// EVERY table and EVERY column the schema declares is named here with what
// happens to it. A table or column this file does not name fails the run, so a
// migration that adds one cannot pass personal data through unexamined; the
// anonymize tests also pin this list to the schema both ways.
//
// `drop` writes the table empty: device chatter, idle reps, coaching-cue state
// and the action log say nothing a training fixture needs. Free text is
// stripped, names become numbered stand-ins, device ids, external ids and
// lifter labels become salted hashes, and every date moves by one whole-week
// offset.

